OBSERVED = "Auf der Folie erkennbar"
OWN = "Eigene Ergänzung"


@dataclass(frozen=True)
class Indicator:
    id: str
    pillar: int
    name: str
    operation: str
    symbols: tuple
    risk_up: bool
    unit: str
    formula: str
    evidence: str = OWN
    evidence_note: str = (
        "Öffentliche Marktgröße für diesen Bereich. Die Aufnahme ins Original ist ungeklärt."
    )
    implementation: str = "Eigene Kennzahl"


def metric(key, pillar, name, op, symbols, risk_up, unit, formula, *, observed=None, implementation=None):
    return Indicator(
        key,
        pillar,
        name,
        op,
        tuple(symbols.split()),
        risk_up,
        unit,
        formula,
        OBSERVED if observed else OWN,
        observed or Indicator.evidence_note,
        implementation or ("Direkte Messgröße" if observed else "Eigene Kennzahl"),
    )


def relative(key, pillar, name, symbols, formula, **kwargs):
    return metric(key, pillar, name, "relative20", symbols, False, "%", formula, **kwargs)


